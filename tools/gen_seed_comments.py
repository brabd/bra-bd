random.seed('bra.bd-seed-comments-v2')
out = {}
for a in ARTICLES:
    slug, title = a['slug'], a['title']
    rnd = random.Random('bb2::' + slug)
    n = rnd.randint(3, 6)  # টাইটেল-কমেন্টসহ মোট 3-6টা
    names = rnd.sample(NAMES, n)
    rows = []
    # ১ম: টাইটেল-ভিত্তিক ইউনিক কমেন্ট (৫০% ক্ষেত্রে লেখকের রিপ্লাইসহ)
    tc, tr = TITLE_TPL[rnd.randrange(len(TITLE_TPL))]
    rows.append({'name': names[0], 'body': tc.format(t=title),
                 'reply': tr if rnd.random() < 0.5 else None})
    # বাকিগুলো: পুল থেকে, এক আর্টিকেলে রিপিটহীন; সর্বোচ্চ ২টা রিপ্লাই মোট
    picks = rnd.sample(range(len(PAIRS)), n - 1)
    replies = 1 if rows[0]['reply'] else 0
    for j, p in enumerate(picks):
        c, r = PAIRS[p]
        use_r = r if (r and replies < 2 and rnd.random() < 0.6) else None
        if use_r: replies += 1
        rows.append({'name': names[j+1], 'body': c, 'reply': use_r})
    out[slug] = rows

dst = os.path.join(ROOT, 'content', 'seed-comments.json')
with io.open(dst, 'w', encoding='utf-8') as f:
    json.dump(out, f, ensure_ascii=False, indent=1)
print('written', dst, '-', len(out), 'slugs')
